// Build-time allow-list: hashed word trigrams of all real curriculum text (src/data + EN translations).
// Lets /api/tts/lesson and lesson-chunk /api/tts narrate curriculum text without a Firebase token.
import fs from 'fs'; import path from 'path';
import { textTrigrams } from '../src/server/lessonTextNorm';
const set = new Set<number>();
const walk = (d: string) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (/\.(ts|tsx|json)$/.test(f)) add(fs.readFileSync(p, 'utf8')); } };
// Per string literal so code tokens don't glue lessons together.
function add(src: string) { const re = /(["'`])((?:\\.|(?!\1)[^\\])*)\1/gs; let m; while ((m = re.exec(src))) for (const h of textTrigrams(m[2].replace(/\\n/g, '\n').replace(/\\(.)/g, '$1'))) set.add(h); }
walk('src/data');
const en = 'public/lesson-en/all.json';
if (fs.existsSync(en)) { const walkJ = (v: any) => { if (typeof v === 'string') textTrigrams(v).forEach(h => set.add(h)); else if (v && typeof v === 'object') Object.values(v).forEach(walkJ); }; walkJ(JSON.parse(fs.readFileSync(en, 'utf8'))); }
const arr = Uint32Array.from([...set]).sort();
fs.mkdirSync('src/server/generated', { recursive: true });
fs.writeFileSync('src/server/generated/lessonTrigrams.ts', `// AUTO-GENERATED by scripts/build-lesson-ngrams.ts — do not edit.\nexport const LESSON_TRIGRAMS_B64 = "${Buffer.from(arr.buffer).toString('base64')}";\n`);
console.log(`[lesson-ngrams] ${arr.length} trigrams`);

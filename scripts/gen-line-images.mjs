// Regenerates src/data/visuals/lineImages.ts from public/visuals/<player>/<lessonId>/<key>.webp
// plus reuse aliases in scripts/line-image-aliases.json ({ "<lessonId>": { "d0": "p0" } }).
import fs from 'fs';
const root = 'public/visuals'; const out = {};
for (const player of ['daily', 'listening']) {
  const dir = `${root}/${player}`; if (!fs.existsSync(dir)) continue;
  for (const id of fs.readdirSync(dir)) {
    if (!fs.statSync(`${dir}/${id}`).isDirectory() || id === 'airport') continue;
    for (const f of fs.readdirSync(`${dir}/${id}`)) if (f.endsWith('.webp')) (out[id] ||= {})[f.replace('.webp', '')] = `/visuals/${player}/${id}/${f}`;
  }
}
const pilot = ['checkin', 'window-seat', 'bags', 'boarding-pass'].map(n => `/visuals/daily/airport/${n}.webp`);
out['daily-a-01'] = { p0: pilot[0], p1: pilot[1], p2: pilot[2], p3: pilot[3], ...(out['daily-a-01'] || {}) };
const aliases = fs.existsSync('scripts/line-image-aliases.json') ? JSON.parse(fs.readFileSync('scripts/line-image-aliases.json', 'utf8')) : {};
for (const [id, m] of Object.entries(aliases)) for (const [k, src] of Object.entries(m)) if (out[id]?.[src] && !out[id][k]) out[id][k] = out[id][src];
const sorted = Object.fromEntries(Object.keys(out).sort().map(k => [k, Object.fromEntries(Object.entries(out[k]).sort())]));
fs.writeFileSync('src/data/visuals/lineImages.ts', `// Generated by scripts/gen-line-images.mjs. Display only.\n// Keys: p<i> = phrase i, d<i> = dialogue/script line i, scene = lesson setting.\nexport const LINE_IMAGES: Record<string, Record<string, string>> = ${JSON.stringify(sorted, null, 1)};\n`);
console.log(Object.keys(sorted).length, 'lessons', Object.values(sorted).reduce((a, m) => a + Object.keys(m).length, 0), 'keys');
